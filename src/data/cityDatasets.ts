// Generate closed-loop learning records for any city
export function generateCityLearningRecords(cityId: CityId, socs: SocietyProfile[]): LearningRecord[] {
  const records: LearningRecord[] = [];
  const causes = [
    'Service Lift Freight Booking Queue',
    'Gate Security Visitor Verification Delay',
    'Union Mathadi Headload Surcharge',
    'Road Excavation Single-Lane Bottleneck',
    'Basement Height Barrier Transshipment Delay',
  ];

  for (let i = 1; i <= 40; i++) {
    const soc = socs[i % socs.length] || socs[0];
    const predDelay = 12 + (i % 15);
    const actualDelay = predDelay + (i % 3 === 0 ? 12 : -3);
    const predCost = soc.societyFee + (soc.mathadiProbability > 40 ? 250 : 0);
    const actualCost = predCost + (i % 4 === 0 ? 300 : 0);

    records.push({
      id: `LRN-${cityId.slice(0, 3)}-${String(i).padStart(3, '0')}`,
      orderId: `RM-${cityId.slice(0, 3)}-${90000 + i * 13}`,
      societyId: soc.id,
      societyName: soc.name,
      completedAt: new Date(Date.now() - i * 3600000 * 3).toISOString(),
      predictedDelayMin: predDelay,
      actualDelayMin: Math.max(0, actualDelay),
      delayVarianceMin: Math.max(0, actualDelay) - predDelay,
      predictedCostInr: predCost,
      actualCostInr: actualCost,
      costVarianceInr: actualCost - predCost,
      predictedMathadiInr: soc.mathadiProbability > 40 ? 250 : 0,
      actualMathadiInr: actualCost > predCost ? 350 : (soc.mathadiProbability > 40 ? 250 : 0),
      predictedUnloadingMin: soc.typicalUnloadingMinutes || 30,
      actualUnloadingMin: (soc.typicalUnloadingMinutes || 30) + (i % 3 === 0 ? 8 : -2),
      primaryDisruptionCause: actualCost > predCost || actualDelay > predDelay + 10 ? causes[i % causes.length] : undefined,
      modelAdjustmentMade: actualCost > predCost ? `Auto-adjusted ${soc.name.split('-')[0].trim()} baseline parameters` : 'Model calibrated within nominal target bounds.',
    });
  }

  return records;
}

